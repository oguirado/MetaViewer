#!/usr/bin/env python3
"""Mirror the complete canonical v0.2 schema set without envelope mutation."""
import argparse
import hashlib
import json
from pathlib import Path
import pprint

ROOT = Path(__file__).resolve().parents[1]
NAMES = ('guest_command_request', 'guest_command_event', 'guest_command_session', 'guest_transport_metadata')

def project(node):
    if isinstance(node, list):
        return [project(v) for v in node]
    if not isinstance(node, dict):
        return node
    result = {}
    for key, value in node.items():
        if key in ('$schema', '$id', 'title', 'description'):
            continue
        if key in ('properties', '$defs'):
            result[key] = {name: project(child) for name, child in value.items()}
        else:
            result[key] = project(value)
    return result

def generated():
    paths = sorted((ROOT / 'contracts/v0.2').glob('*.schema.json'))
    if not paths:
        raise ValueError('empty canonical schema set')
    files = {p.name: project(json.loads(p.read_text())) for p in paths}
    expected = {name + '.schema.json' for name in ('headless_request', 'headless_event', 'guest_command_request', 'guest_command_event')}
    actual = {branch['$ref'] for branch in files['capsule_envelope.schema.json']['properties']['body']['oneOf']}
    if actual != expected:
        raise ValueError('closed capsule envelope body set mismatch')
    hashes = ''.join('# ' + p.name + ' SHA256 ' + hashlib.sha256(p.read_bytes()).hexdigest() + '\n' for p in paths)
    return ('"""Canonical v0.2 schema projections; generated by tools/generate_guest_command_sdk.py."""\n\n'
            + hashes + '\nFILES = ' + pprint.pformat(files, width=100, sort_dicts=True) + '\n')

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT / 'agents/metaviewer_agents/_contracts_v02.py'
    expected = generated()
    if args.check:
        if path.read_text() != expected:
            raise SystemExit('canonical SDK schema mirror drift')
    else:
        path.write_text(expected)

if __name__ == '__main__':
    main()
