#!/usr/bin/env python3
"""Generate only additive core headless wrappers; existing payload types stay intact."""
import argparse
import hashlib
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
NAMES=('headless_request','headless_event','headless_session')
HEADER='''//! Additive headless contract wrappers. Generated by tools/generate_headless_contracts.py.
//! Fields are validated against the embedded canonical schemas on deserialization.
use serde::{Deserialize, Deserializer, Serialize};
use serde_json::Value;
macro_rules! message {
    ($name:ident, $schema:literal) => {
        #[derive(Clone, Debug, PartialEq, Eq, Serialize)]
        #[serde(transparent)]
        pub struct $name(pub Value);
        impl<'de> Deserialize<'de> for $name {
            fn deserialize<D: Deserializer<'de>>(d: D) -> Result<Self, D::Error> {
                let value = Value::deserialize(d)?;
                let schema = super::schemas::schema(concat!($schema, ".schema.json"))
                    .ok_or_else(|| serde::de::Error::custom("missing headless schema"))?;
                if !super::valid(&value, &schema, &schema) {
                    return Err(serde::de::Error::custom("invalid headless contract"));
                }
                Ok(Self(value))
            }
        }
    };
}
message!(HeadlessRequest, "headless_request");
message!(HeadlessEvent, "headless_event");
message!(HeadlessSession, "headless_session");
'''
def main():
 parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
 pins=''.join('// '+name+' SHA256 '+hashlib.sha256((ROOT/'contracts/v0.2'/f'{name}.schema.json').read_bytes()).hexdigest()+'\n'for name in NAMES)
 expected=HEADER+pins;target=ROOT/'core/src/wire/headless.rs'
 if args.check:
  if target.read_text()!=expected:raise SystemExit('headless generated wrappers are stale')
 else:target.write_text(expected)
if __name__=='__main__':main()
