// MVUI25B lane C: host adapter chord grammar — every key chord keyMap can emit
// for the supported input space, joined with "+", matches ^[A-Za-z0-9_+]{1,32}$
// with at most 8 keys (daemon manager constraint). The mapper is imported via
// the tileScheduler re-export (defect 1 fix), so this file also exercises that
// path. MVUI25C lane P: ASCII punctuation/space inside chords map to X keysym
// names, non-ASCII with modifiers maps to null, over-limit chords map to null;
// the invariant below enumerates the full input space. Plain node:test; pure
// mapping, no async waits needed.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mapKeyboardEvent } from '../src/surfaces/tileScheduler.js';

/** Host adapter chord grammar: joined keys, 1..32 chars. */
const CHORD_RE = /^[A-Za-z0-9_+]{1,32}$/;
/** Host adapter chord width: at most 8 keys. */
const MAX_KEYS = 8;

/**
 * DOM `key` values keyMap routes through NAMED_KEYS (single table in
 * ui/src/input/keyMap.js, F1..F12 generated by loop).
 * @type {string[]}
 */
const NAMED_DOM_KEYS = [
  'Enter', 'Backspace', 'Tab', 'Delete', 'Del', 'Insert', 'Ins', 'Home', 'End',
  'PageUp', 'PageDown', 'ArrowLeft', 'ArrowRight', 'ArrowUp', 'ArrowDown',
  'Left', 'Right', 'Up', 'Down',
  'F1', 'F2', 'F3', 'F4', 'F5', 'F6', 'F7', 'F8', 'F9', 'F10', 'F11', 'F12',
];

/**
 * Printable single-chars whose lowercased spelling stays in the grammar
 * (letters/digits/space, plus the two grammar symbols + and _).
 * @type {string[]}
 */
const GRAMMAR_SAFE_CHARS = ['a', 'Z', '0', ' ', '+', '_'];

/**
 * All 16 ctrl/alt/shift/meta combinations.
 * @returns {Array<{ ctrlKey: boolean, altKey: boolean, shiftKey: boolean, metaKey: boolean }>}
 */
function allModifierCombos() {
  /** @type {Array<{ ctrlKey: boolean, altKey: boolean, shiftKey: boolean, metaKey: boolean }>} */
  const combos = [];
  for (let mask = 0; mask < 16; mask += 1) {
    combos.push({
      ctrlKey: (mask & 1) !== 0,
      altKey: (mask & 2) !== 0,
      shiftKey: (mask & 4) !== 0,
      metaKey: (mask & 8) !== 0,
    });
  }
  return combos;
}

test('mvui25b chords: every named-key chord matches the host grammar', () => {
  let count = 0;
  for (const key of NAMED_DOM_KEYS) {
    for (const mods of allModifierCombos()) {
      const mapped = mapKeyboardEvent({ key, ...mods });
      assert.ok(mapped !== null && mapped.kind === 'key', `${key} with mods maps to a key chord`);
      assert.ok(Array.isArray(mapped.keys), 'chord carries keys');
      assert.ok(mapped.keys.length >= 1 && mapped.keys.length <= MAX_KEYS,
        `${key} chord has 1..${MAX_KEYS} keys`);
      const joined = mapped.keys.join('+');
      assert.match(joined, CHORD_RE, `chord ${joined} matches host grammar`);
      count += 1;
    }
  }
  assert.ok(count === NAMED_DOM_KEYS.length * 16, `enumerated ${count} named chords`);
});

test('mvui25b chords: grammar-safe chars with modifiers match; bare chars type', () => {
  // Single-chars become chords only with ctrl/alt/meta; shift alone still
  // types (keyMap checks !ctrl && !alt && !meta).
  const chordCombos = allModifierCombos().filter((m) => m.ctrlKey || m.altKey || m.metaKey);
  assert.equal(chordCombos.length, 14, '14 chord-forcing modifier combos');
  for (const ch of GRAMMAR_SAFE_CHARS) {
    const bare = mapKeyboardEvent({ key: ch });
    assert.ok(bare !== null && bare.kind === 'type', `'${ch}' without modifiers types`);
    const shifted = mapKeyboardEvent({ key: ch, shiftKey: true });
    assert.ok(shifted !== null && shifted.kind === 'type', `'${ch}' with shift-only types`);
    for (const mods of chordCombos) {
      const mapped = mapKeyboardEvent({ key: ch, ...mods });
      assert.ok(mapped !== null && mapped.kind === 'key', `'${ch}' with modifiers is a chord`);
      assert.ok(mapped.keys.length <= MAX_KEYS, 'chord width within limit');
      assert.match(mapped.keys.join('+'), CHORD_RE, 'chord matches host grammar');
    }
  }
});

test('mvui25b chords negative: malformed chords are rejected by the grammar', () => {
  const bad = [
    '', 'ctrl+,', 'ctrl+é', 'ctrl+中', 'ctrl+ ', 'ctrl+a ',
    `ctrl+${'a'.repeat(30)}`,
  ];
  for (const joined of bad) {
    assert.doesNotMatch(joined, CHORD_RE, `"${joined}" is rejected`);
  }
  const nineKeys = ['a', 'b', 'c', 'd', 'e', 'f', 'g', 'h', 'i'];
  assert.ok(nineKeys.length > MAX_KEYS, '9-key chord exceeds the width limit');
  assert.ok('a+b+c+d+e+f+g+h+i'.length <= 32, 'width limit is independent of length');
});

test('mvui25c chords invariant: every emitted chord matches the host grammar', () => {
  // Full input space: all printable ASCII, a non-ASCII sample, every named
  // key, every modifier combination. Every emitted chord must match the
  // grammar; non-ASCII with modifiers and over-limit chords map to null.
  /** @type {string[]} */
  const ascii = [];
  for (let point = 0x20; point <= 0x7e; point += 1) {
    ascii.push(String.fromCodePoint(point));
  }
  assert.equal(ascii.length, 95, '95 printable ASCII chars');
  const nonAscii = ['é', '中', '€', '😀', 'ñ', 'Ω'];
  const combos = allModifierCombos();
  let chords = 0;
  let types = 0;
  let nulls = 0;
  for (const key of [...ascii, ...nonAscii, ...NAMED_DOM_KEYS]) {
    for (const mods of combos) {
      const mapped = mapKeyboardEvent({ key, ...mods });
      if (mapped === null) {
        nulls += 1;
        continue;
      }
      if (mapped.kind === 'type') {
        assert.ok(!mods.ctrlKey && !mods.altKey && !mods.metaKey,
          `'${key}' types only without ctrl/alt/super`);
        assert.equal(mapped.text, key, 'type payload is the input char unchanged');
        types += 1;
        continue;
      }
      assert.equal(mapped.kind, 'key', 'mapping is key, type, or null');
      assert.ok(Array.isArray(mapped.keys), 'chord carries keys');
      assert.ok(mapped.keys.length >= 1 && mapped.keys.length <= MAX_KEYS,
        `chord has 1..${MAX_KEYS} keys`);
      const joined = mapped.keys.join('+');
      assert.ok(joined.length <= 32, `chord ${joined} fits 32 chars`);
      assert.match(joined, CHORD_RE, `chord ${joined} matches host grammar`);
      chords += 1;
    }
  }
  const total = (ascii.length + nonAscii.length + NAMED_DOM_KEYS.length) * combos.length;
  assert.equal(chords + types + nulls, total, `enumerated ${total} inputs`);
  assert.ok(chords > 0 && types > 0 && nulls > 0, 'all three outcomes covered');
  // Pinned fix witnesses: punctuation maps to keysym names, non-ASCII with
  // a modifier is dropped, bare non-ASCII still types.
  assert.deepEqual(mapKeyboardEvent({ key: ',', ctrlKey: true }),
    { kind: 'key', keys: ['ctrl', 'comma'] });
  assert.deepEqual(mapKeyboardEvent({ key: ']', ctrlKey: true }),
    { kind: 'key', keys: ['ctrl', 'bracketright'] });
  assert.equal(mapKeyboardEvent({ key: 'é', ctrlKey: true }), null);
  assert.deepEqual(mapKeyboardEvent({ key: 'é' }), { kind: 'type', text: 'é' });
  // Length boundary: 32-char chord passes, 33-char chord maps to null.
  assert.deepEqual(
    mapKeyboardEvent({ key: '[', ctrlKey: true, altKey: true, shiftKey: true, metaKey: true }),
    { kind: 'key', keys: ['ctrl', 'alt', 'shift', 'super', 'bracketleft'] });
  assert.equal(
    mapKeyboardEvent({ key: ']', ctrlKey: true, altKey: true, shiftKey: true, metaKey: true }),
    null);
  // Negative control: planted raw-character chords fail the grammar, so the
  // invariant above is capable of catching the old violation.
  for (const planted of ['ctrl+,', 'ctrl+é', 'ctrl+中']) {
    assert.doesNotMatch(planted, CHORD_RE, `planted "${planted}" is rejected`);
  }
});
