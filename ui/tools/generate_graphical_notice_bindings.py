#!/usr/bin/env python3
"""Generate only the additive main-process graphical notice validator."""
from pathlib import Path
import argparse
import hashlib
import json

ROOT = Path(__file__).resolve().parents[2]
NAMES = ('graphical_session_notice.schema.json', 'graphical_session_notice_envelope.schema.json')
TARGET = ROOT / 'ui/electron/graphicalSessionNoticeValues.js'

def generated():
    paths = [ROOT / 'contracts/v0.2' / name for name in NAMES]
    schemas = {path.name: json.loads(path.read_text()) for path in paths}
    schema_json = json.dumps(schemas, ensure_ascii=True, separators=(',', ':'), sort_keys=True)
    pins = '\n'.join('// ' + path.name + ' sha256 ' + hashlib.sha256(path.read_bytes()).hexdigest() for path in paths)
    return '''// Generated by ui/tools/generate_graphical_notice_bindings.py; main process only.
''' + pins + '''
import {createGraphicalSessionChecks} from './graphicalSessionChecks.js';
const NOTICE_SCHEMAS_JSON = ''' + json.dumps(schema_json) + ''';
/** @type {Record<string,any>|undefined} */
let schemas;
const checks=createGraphicalSessionChecks(()=>schemas??=(JSON.parse(NOTICE_SCHEMAS_JSON)));
/** @param {any} value @returns {boolean} */
export const graphicalNoticeValid=value=>checks.graphicalValid('graphical_session_notice.schema.json',value);
/** @param {any} value @returns {boolean} */
export const graphicalNoticeEnvelopeValid=value=>checks.graphicalValid('graphical_session_notice_envelope.schema.json',value);
export const graphicalNoticePlain=checks.graphicalPlain;
'''

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    value = generated()
    if args.check:
        if not TARGET.is_file() or TARGET.read_text() != value:
            raise SystemExit('graphical notice bindings differ; regenerate')
    else:
        TARGET.write_text(value)

if __name__ == '__main__':
    main()
